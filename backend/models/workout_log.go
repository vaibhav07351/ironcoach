package models

import (
	"time"

	"go.mongodb.org/mongo-driver/bson/primitive"
)

// SetEntry is one set of an exercise. Which fields are used depends on the exercise type:
// weight x reps, reps (optional added weight), distance + time, or time only.
type SetEntry struct {
	WeightKg  float64 `json:"weight_kg" bson:"weight_kg"`
	Reps      int     `json:"reps" bson:"reps"`
	DistanceM float64 `json:"distance_m,omitempty" bson:"distance_m,omitempty"`
	DurationS int     `json:"duration_s,omitempty" bson:"duration_s,omitempty"`
	Note      string  `json:"note,omitempty" bson:"note,omitempty"`
}

// Workout represents a single exercise in a workout log.
//
// Entries is the current set format. Sets/Reps/Weight are the original parallel arrays: the
// server keeps writing them (mirrored from Entries) so older app versions and older readers keep
// working, and EntriesOf converts old documents that only have the arrays.
type Workout struct {
	Exercise   string             `json:"exercise" bson:"exercise"`             // Exercise name
	ExerciseID primitive.ObjectID `json:"exercise_id" bson:"exercise_id"`       // Link to Exercise
	Type       string             `json:"type,omitempty" bson:"type,omitempty"` // Exercise type when logged
	Sets       int                `json:"sets" bson:"sets"`                     // Number of sets
	Reps       []int              `json:"reps" bson:"reps"`                     // Reps for each set
	Weight     []float64          `json:"weight" bson:"weight"`                 // Weight used for each set
	Entries    []SetEntry         `json:"entries,omitempty" bson:"entries,omitempty"`
	Notes      string             `json:"notes,omitempty" bson:"notes,omitempty"` // Additional notes
}

// EntriesOf returns a workout's sets in the current format, converting the legacy parallel
// arrays (pairing only indexes present in both) when Entries is empty.
func EntriesOf(w Workout) []SetEntry {
	if len(w.Entries) > 0 {
		return w.Entries
	}
	n := len(w.Reps)
	if len(w.Weight) < n {
		n = len(w.Weight)
	}
	out := make([]SetEntry, 0, n)
	for i := 0; i < n; i++ {
		out = append(out, SetEntry{WeightKg: w.Weight[i], Reps: w.Reps[i]})
	}
	return out
}

// WorkoutLog represents a log entry for a trainee's workout or sport session.
type WorkoutLog struct {
	ID           string          `bson:"_id,omitempty" json:"id"`
	TraineeID    string          `json:"trainee_id" bson:"trainee_id"`
	Date         string          `json:"date" bson:"date"`
	ActivityType string          `json:"activity_type,omitempty" bson:"activity_type,omitempty"`
	Workouts     []Workout       `json:"workouts,omitempty" bson:"workouts,omitempty"`
	Metrics      *SessionMetrics `json:"metrics,omitempty" bson:"metrics,omitempty"`
	Notes        string          `json:"notes,omitempty" bson:"notes,omitempty"`
	// ExerciseKey is set on logs written by the per-exercise day endpoint: the exercise id. Those
	// logs hold exactly one exercise and are unique per (trainee, date, exercise).
	ExerciseKey string `json:"exercise_key,omitempty" bson:"exercise_key,omitempty"`
	// ClientID is an optional idempotency key generated by the app, so a retried create
	// (e.g. after a timeout or from the offline queue) never inserts a duplicate.
	ClientID  string    `json:"client_id,omitempty" bson:"client_id,omitempty"`
	CreatedAt time.Time `json:"created_at" bson:"created_at"`
	UpdatedAt time.Time `json:"updated_at" bson:"updated_at"`
}

// WorkoutLogInput is the accepted body for creating a log. Server-owned fields (id,
// timestamps) are never read from the client.
type WorkoutLogInput struct {
	TraineeID    string          `json:"trainee_id" binding:"required"`
	Date         string          `json:"date" binding:"required"`
	ActivityType string          `json:"activity_type"`
	Workouts     []Workout       `json:"workouts"`
	Metrics      *SessionMetrics `json:"metrics"`
	Notes        string          `json:"notes"`
	ClientID     string          `json:"client_id"`
}

// WorkoutLogUpdate is the accepted body for editing a log. Only provided fields change;
// trainee_id and activity type are fixed after creation.
type WorkoutLogUpdate struct {
	Date     *string         `json:"date"`
	Workouts *[]Workout      `json:"workouts"`
	Metrics  *SessionMetrics `json:"metrics"`
	Notes    *string         `json:"notes"`
}

// ExerciseDayInput replaces all sets of one exercise on one day. An empty Entries list removes
// that exercise from the day.
type ExerciseDayInput struct {
	Entries []SetEntry `json:"entries"`
	Notes   string     `json:"notes"`
}
